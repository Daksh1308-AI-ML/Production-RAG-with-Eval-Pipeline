"""A/B evaluation report: collate results_ab score files into a comparison report.

Reads data/evaluation/results_ab/ (produced by run_ab.py) and writes:
  - summary markdown table (strategy x metric, mean + best)
  - per_strategy_metrics.csv (already written by run_ab; re-derived here)
  - ab_report.md with winner per metric and per-metric samples

Usage: python scripts/ab_report.py [--out data/evaluation/results_ab] [--write-report]
"""

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

_METRICS = ("faithfulness", "answer_relevancy", "context_precision", "context_recall")
_STRATEGIES = ("baseline", "hybrid", "rerank", "full")


def _load_json(path, default):
    if path.exists():
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return default


def load_scores(out_dir: Path, strategies, metrics):
    """strategy -> metric -> {mean, n, samples}."""
    result = {}
    for strategy in strategies:
        result[strategy] = {}
        for metric in metrics:
            state = _load_json(out_dir / f"scores_{strategy}_{metric}.json", {"samples": []})
            samples = [s for s in state["samples"] if s.get("score") is not None]
            values = [s["score"] for s in samples]
            result[strategy][metric] = {
                "mean": round(sum(values) / len(values), 4) if values else None,
                "n": len(values),
                "samples": samples,
            }
    return result


def best_per_metric(data):
    """metric -> strategy with highest non-null mean."""
    rankings = {}
    for metric in _METRICS:
        ranked = sorted(
            ((strategy, data[strategy][metric]["mean"])
             for strategy in _STRATEGIES
             if data[strategy][metric]["mean"] is not None),
            key=lambda x: x[1], reverse=True,
        )
        rankings[metric] = ranked[0] if ranked else (None, None)
    return rankings


def write_report(out_dir: Path, data, rankings, write_file: bool = True):
    lines = ["# A/B Evaluation Report", ""]
    lines.append(f"Sources: `{out_dir.resolve()}`  \n")

    lines.append("## Mean score per strategy/metric")
    lines.append("| strategy | " + " | ".join(_METRICS) + " |")
    lines.append("|----------|" + "|".join(["-----------"] * len(_METRICS)) + "|")
    for strategy in _STRATEGIES:
        row = [strategy]
        for metric in _METRICS:
            v = data[strategy][metric]["mean"]
            row.append("---" if v is None else f"{v:.4f}")
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")
    lines.append("## Best strategy per metric")
    for metric, (strategy, mean) in rankings.items():
        if strategy:
            lines.append(f"- **{metric}**: {strategy} ({mean:.4f})")
        else:
            lines.append(f"- **{metric}**: no scored samples")

    lines.append("")
    lines.append("> Generated by `scripts/ab_report.py` "
                 "from `run_ab.py` checkpoint files.")

    report = "\n".join(lines)
    if write_file:
        (out_dir / "ab_report.md").write_text(report + "\n", encoding="utf-8")
    print(report)
    return report


def main():
    parser = argparse.ArgumentParser(description="A/B evaluation report")
    parser.add_argument("--out", default="data/evaluation/results_ab")
    parser.add_argument("--no-write", action="store_true", help="print only, no files")
    args = parser.parse_args()

    out_dir = Path(args.out)
    data = load_scores(out_dir, _STRATEGIES, _METRICS)
    rankings = best_per_metric(data)
    write_report(out_dir, data, rankings, write_file=not args.no_write)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())